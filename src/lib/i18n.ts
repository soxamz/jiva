export function isLocale(value: string): value is Locale {
  return languages.some((language) => language.code === value);
}

export function getLanguage(locale: Locale) {
  return languages.find((language) => language.code === locale) ?? languages[0];
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {}
) {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`)
  );
}

function localeFromHeader(value: string | null): Locale {
  const candidates =
    value
      ?.toLowerCase()
      .split(',')
      .map((entry) => entry.trim().slice(0, 2)) ?? [];
  return candidates.find(isLocale) ?? 'en';
}

export async function getLocale(): Promise<Locale> {
  const stored = (await cookies()).get(localeCookieName)?.value;

  if (stored && isLocale(stored)) {
    return stored;
  }

  return localeFromHeader((await headers()).get('accept-language'));
}

export async function getI18n() {
  const locale = await getLocale();
  return {
    locale,
    language: getLanguage(locale),
    messages: dictionaries[locale],
    t: (key: MessageKey, values?: Record<string, string | number>) =>
      translate(locale, key, values),
  };
}

export async function setLocale(locale: Locale) {
  (await cookies()).set(localeCookieName, locale, {
    httpOnly: true,
    sameSite: 'lax',
    secure: process.env.NODE_ENV === 'production',
    path: '/',
    maxAge: 60 * 60 * 24 * 365,
  });
}
